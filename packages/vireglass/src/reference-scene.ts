/**
 * СВЕРОЧНАЯ СЦЕНА — одно полотно, которое оба стенда рисуют одинаково.
 *
 * Веб-стенд и мобильная лаборатория отвечают на разные вопросы (измеритель против проверки
 * платформы), и это правильно. Но полотна у них были РАЗНЫЕ, поэтому вопрос «на Android
 * стекло выглядит иначе?» подтвердить было нечем: снимки несравнимы по построению.
 *
 * Сцена описана ДАННЫМИ, а не кодом отрисовки: канвас и вьюхи рисуют по-разному, а список
 * прямоугольников обе платформы кладут одинаково. Ничего, кроме заливок, здесь нет намеренно —
 * градиент, текст и скругление на двух платформах разъедутся, и сравнение опять поплывёт.
 *
 * Полосы подобраны под три величины, которые и сверяются между платформами:
 *   — РОВНЫЕ поля: отход тела детали от фона на пяти уровнях светлоты;
 *   — СТУПЕНЬ: сколько разброса фона доходит до пикселя у кромки;
 *   — ПОЛОСА: во сколько раз кромка раздувает изображение того, что за ней.
 */

import { capsuleGeometry, circleGeometry, roundedRectGeometry, type VireGlassGeometry } from './geometry';

/**
 * ФИГУРЫ СТЕНДОВ — тоже общие. Размер детали входит в оптику через sizeGain: круг 120 и круг
 * 150 это стекло разной толщины, и снимки двух стендов на разных фигурах несравнимы так же,
 * как на разных полотнах. Значения совпадают с теми, на которых сняты сверки с эталоном.
 */
export const REFERENCE_SHAPES = {
  круг: circleGeometry(120),
  капсула: capsuleGeometry(300, 110),
  плашка: roundedRectGeometry(220, 120, 32),
} satisfies Record<string, VireGlassGeometry>;

export type VireGlassRefShapeName = keyof typeof REFERENCE_SHAPES;

/** Доля высоты полотна и заливка. `split` — вторая заливка на правой половине полосы. */
export type VireGlassRefBand = {
  readonly name: string;
  /** Доля высоты всей сцены. Сумма по всем полосам равна единице. */
  readonly height: number;
  /** Светлота заливки, 0…1. Серый, а не цвет: цвет мерить нечем без общей колориметрии. */
  readonly level: number;
  /** Светлота правой половины, если полоса со ступенью. */
  readonly splitLevel?: number;
  /** Тёмная черта поперёк полосы: доля высоты полосы и её светлота. */
  readonly bar?: { readonly thickness: number; readonly level: number };
};

export const REFERENCE_BANDS: readonly VireGlassRefBand[] = [
  { name: 'ровное 0.10', height: 0.14, level: 0.1 },
  { name: 'ровное 0.30', height: 0.14, level: 0.3 },
  { name: 'ровное 0.50', height: 0.14, level: 0.5 },
  { name: 'ровное 0.69', height: 0.14, level: 0.69 },
  { name: 'ровное 0.90', height: 0.14, level: 0.9 },
  { name: 'ступень 0.05 → 0.28', height: 0.15, level: 0.05, splitLevel: 0.28 },
  { name: 'полоса на светлом', height: 0.15, level: 0.92, bar: { thickness: 0.17, level: 0.12 } },
];

/** Светлота в шестнадцатеричный серый. Один перевод на обе платформы — иначе разойдутся. */
export const refGray = (level: number): string => {
  const v = Math.round(Math.min(Math.max(level, 0), 1) * 255)
    .toString(16)
    .padStart(2, '0');
  return `#${v}${v}${v}`;
};
