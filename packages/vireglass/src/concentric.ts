// Концентричность (эталон 219 @7:53): вложенные формы делят ЦЕНТР кривизны, а не радиус.
// Поэтому у внутренней формы радиус меньше ровно на отступ — иначе углы идут не параллельно и
// зазор между формами то съедается, то расходится.

/**
 * Радиус вложенной формы: внешний радиус минус отступ. Ноль — квадратный угол; отрицательным он
 * не бывает, у отступа больше внешнего радиуса угол просто прямой.
 */
export function concentricRadius(outerRadius: number, inset: number): number {
  return Math.max(outerRadius - inset, 0);
}

/**
 * Отступ, при котором внутренняя форма с заданным радиусом останется концентричной внешней.
 * Обратная задача: радиус детали известен (её диктует размер), нужно поле вокруг неё.
 */
export function concentricInset(outerRadius: number, innerRadius: number): number {
  return Math.max(outerRadius - innerRadius, 0);
}
